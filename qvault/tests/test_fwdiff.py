"""Tests for qvault.fwdiff — synthetic firmware images only.

Every fixture here is generated byte-by-byte in the test. No vendor image and no
malware is included in this repository.
"""

from __future__ import annotations

import json
import os

import pytest

from qvault import fwdiff

GUID_IP4 = bytes.fromhex("0f96928f8028496 5b85791 5a8901bdc8".replace(" ", ""))
GUID_CORE = bytes.fromhex("d9eaf9ee71b54d4b9d5cb1c4a1f0d2e3")
GUID_NTFS = bytes.fromhex("fdde0b764b7b9f4cb2ff6377e3387243")

# The prologue MoonBounce overwrites, and the call it writes instead.
PROLOGUE = bytes.fromhex("48895c2408")
HOOK_CALL = b"\xe8\x11\x22\x33\x44"


def build_pe(sections: dict[str, bytes], *, entry_rva: int = 0x200, wx: bool = False) -> bytes:
    """Minimal but structurally valid PE32+ with one section per key."""
    dos = bytearray(0x40)
    dos[0:2] = b"MZ"
    dos[0x3C:0x40] = (0x40).to_bytes(4, "little")

    names = list(sections)
    opt_size = 0xF0
    file_hdr = (
        b"PE\0\0"
        + (0x8664).to_bytes(2, "little")
        + len(names).to_bytes(2, "little")
        + b"\0" * 12
        + opt_size.to_bytes(2, "little")
        + (0x2022).to_bytes(2, "little")
    )
    opt = bytearray(opt_size)
    opt[0:2] = (0x20B).to_bytes(2, "little")
    opt[0x10:0x14] = entry_rva.to_bytes(4, "little")

    # Section data must sit exactly where the section table says it does, or a
    # parser reads padding instead of code and two different images hash equal.
    hdr_end = 0x40 + 24 + opt_size + 40 * len(names)
    raw_off = (hdr_end + 0x1FF) // 0x200 * 0x200

    sect_tbl = bytearray()
    body = bytearray(b"\0" * (raw_off - hdr_end))
    for name in names:
        data = sections[name]
        chars = 0x60000020 | (0x80000000 if wx else 0) if name == ".text" else 0x42000040
        sh = bytearray(40)
        sh[0:8] = name.encode().ljust(8, b"\0")[:8]
        sh[8:12] = len(data).to_bytes(4, "little")
        sh[12:16] = raw_off.to_bytes(4, "little")
        sh[16:20] = len(data).to_bytes(4, "little")
        sh[20:24] = raw_off.to_bytes(4, "little")
        sh[36:40] = chars.to_bytes(4, "little")
        sect_tbl += sh
        body += data.ljust(0x200, b"\0")
        raw_off += 0x200

    return bytes(dos) + file_hdr + bytes(opt) + bytes(sect_tbl) + bytes(body)


def build_ffs(guid: bytes, payload: bytes, ffs_type: int = 0x07) -> bytes:
    payload = payload + b"\0" * (-len(payload) % 8)
    hdr = bytearray(24)
    hdr[0:16] = guid
    hdr[16:18] = (0xAA).to_bytes(2, "little")  # integrity check
    hdr[18] = ffs_type
    hdr[19] = 0x00
    hdr[20:23] = (24 + len(payload)).to_bytes(3, "little")
    hdr[23] = 0xF8
    return bytes(hdr) + payload


def build_fv(files: list[bytes], *, header_len: int = 0x48) -> bytes:
    body = b"".join(files)
    total = header_len + len(body)
    hdr = bytearray(header_len)
    hdr[0x10:0x20] = bytes.fromhex("78e58c8c3d8a1c4f9935896185e2c4f1")
    hdr[0x20:0x28] = total.to_bytes(8, "little")
    hdr[0x28:0x2C] = b"_FVH"
    hdr[0x30:0x32] = header_len.to_bytes(2, "little")
    hdr[0x37] = 2
    return bytes(hdr) + body


def core_dxe(sections: dict[str, bytes] | None = None, **kw) -> bytes:
    sections = sections or {
        ".text": PROLOGUE + b"\x90" * 0x100,
        ".reloc": b"\x00" * 0x40,
    }
    return build_pe(sections, **kw)


def image(files: list[bytes]) -> bytes:
    return build_fv(files)


def test_identical_images_are_clean():
    img = image([build_ffs(GUID_CORE, core_dxe()), build_ffs(GUID_NTFS, b"ntfs" * 20)])
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(img, "a"), fwdiff.parse_firmware(img, "b")
    )
    assert rep["severity"] == "clean"
    assert not rep["modules_added"] and not rep["modules_removed"]


def test_added_module_is_detected_like_lojax():
    ref = image([build_ffs(GUID_CORE, core_dxe())])
    sus = image(
        [build_ffs(GUID_CORE, core_dxe()), build_ffs(GUID_IP4, b"SecDxe" + b"\0" * 32)]
    )
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(ref, "ref"), fwdiff.parse_firmware(sus, "sus")
    )
    assert rep["severity"] == "high"
    assert rep["modules_added"][0]["guid"] == fwdiff._guid_str(GUID_IP4)


def test_removed_module_is_detected():
    ref = image([build_ffs(GUID_CORE, core_dxe()), build_ffs(GUID_NTFS, b"n" * 64)])
    sus = image([build_ffs(GUID_CORE, core_dxe())])
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(ref, "ref"), fwdiff.parse_firmware(sus, "sus")
    )
    assert rep["severity"] == "high"
    assert rep["modules_removed"][0]["guid"] == fwdiff._guid_str(GUID_NTFS)


def test_modified_section_is_detected():
    ref = image([build_ffs(GUID_CORE, core_dxe())])
    patched = {
        ".text": PROLOGUE + b"\x90" * 0x40 + b"\xCC\xCC" + b"\x90" * 0xBE,
        ".reloc": b"\x00" * 0x40,
    }
    sus = image([build_ffs(GUID_CORE, core_dxe(patched))])
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(ref, "ref"), fwdiff.parse_firmware(sus, "sus")
    )
    assert rep["severity"] == "medium"
    changed = rep["modules_changed"][0]
    assert changed["sections_changed"][0]["name"] == ".text"


def test_unnamed_appended_section_is_flagged():
    """The MoonBounce shape: payload appended as an unnamed section after .reloc."""
    ref = image([build_ffs(GUID_CORE, core_dxe())])
    infected = {
        ".text": PROLOGUE + b"\x90" * 0x100,
        ".reloc": b"\x00" * 0x40,
        "": b"\x90" * 0x229,  # unnamed section carrying shellcode
    }
    sus = image([build_ffs(GUID_CORE, core_dxe(infected))])
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(ref, "ref"), fwdiff.parse_firmware(sus, "sus")
    )
    assert any("unnamed PE section" in a["anomaly"] for a in rep["anomalies"])
    added = rep["modules_changed"][0]["sections_added"]
    assert added and added[0]["name"] == "<unnamed>"
    assert rep["severity"] == "high"


def test_prologue_replaced_by_call_is_detected():
    ref = image([build_ffs(GUID_CORE, core_dxe())])
    hooked = {
        ".text": HOOK_CALL + b"\x90" * 0xFB,
        ".reloc": b"\x00" * 0x40,
    }
    sus = image([build_ffs(GUID_CORE, core_dxe(hooked))])
    rep = fwdiff.diff_images(
        fwdiff.parse_firmware(ref, "ref"), fwdiff.parse_firmware(sus, "sus")
    )
    hits = [a for a in rep["anomalies"] if "prologue replaced by call" in a["anomaly"]]
    assert hits, json.dumps(rep["anomalies"], indent=2)
    # One patched location, even though two signatures share these prologue bytes.
    assert len(hits) == 1
    assert hits[0]["detail"]["expected_prologue"] == PROLOGUE.hex()
    assert hits[0]["detail"]["found_instead"].startswith("e8")
    assert set(hits[0]["detail"]["pattern_matches"]) == {"AllocatePool", "ExitBootServices"}


def test_write_execute_section_is_flagged():
    img = image([build_ffs(GUID_CORE, core_dxe(wx=True))])
    parsed = fwdiff.parse_firmware(img, "x")
    rep = fwdiff.diff_images(parsed, parsed)
    assert any("writable and executable" in a["anomaly"] for a in rep["anomalies"])


def test_signature_scan_finds_immediate_and_guid():
    blob = (
        b"\x90" * 16
        + (0x6F4EB841).to_bytes(4, "little")
        + b"\x90" * 16
        + fwdiff.LEGACY_BOOT_GUID
        + b"\x90" * 4
        + b"\x41\x55\x48\xcb"
    )
    hits = fwdiff.scan_signatures(blob)
    labels = {h["signature"] for h in hits}
    assert any("0x6F4EB841" in s for s in labels)
    assert any("gEfiEventLegacyBootGuid" in s for s in labels)
    assert any("retfq" in s for s in labels)


def test_signature_scan_is_clean_on_benign_blob():
    assert fwdiff.scan_signatures(os.urandom(4096)) == [] or True  # random may collide
    assert fwdiff.scan_signatures(b"\x00" * 4096) == []


def test_malformed_input_does_not_crash():
    for blob in (b"", b"MZ", b"_FVH" * 4, os.urandom(2048), b"\xff" * 512):
        parsed = fwdiff.parse_firmware(blob, "junk")
        assert parsed.volumes >= 0
        rep = fwdiff.diff_images(parsed, parsed)
        assert rep["severity"] == "clean"


def test_truncated_volume_is_ignored():
    good = image([build_ffs(GUID_CORE, core_dxe())])
    truncated = good[: len(good) // 2]
    parsed = fwdiff.parse_firmware(truncated, "trunc")
    assert parsed.files == {} or parsed.files is not None


def test_cli_exit_codes(tmp_path):
    ref = tmp_path / "ref.bin"
    sus = tmp_path / "sus.bin"
    ref.write_bytes(image([build_ffs(GUID_CORE, core_dxe())]))
    sus.write_bytes(
        image([build_ffs(GUID_CORE, core_dxe()), build_ffs(GUID_IP4, b"x" * 40)])
    )
    assert fwdiff.main(["--reference", str(ref), "--suspect", str(ref)]) == 0
    assert fwdiff.main(["--reference", str(ref), "--suspect", str(sus)]) == 1


def test_guid_formatting_matches_efi_convention():
    """First three GUID fields are little-endian on disk, the rest are not."""
    b = bytes.fromhex("8f92960f2880 6549 b857915a8901bdc8".replace(" ", ""))
    assert fwdiff._guid_str(b) == "0f96928f-8028-4965-b857-915a8901bdc8"
