#!/usr/bin/env python3
"""Render report/IN_THE_WILD.md from the pinned Project Zero reference set."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qvault import wild as W  # noqa: E402
import tables  # noqa: E402

OUT = ROOT / "report" / "IN_THE_WILD.md"


def render() -> str:
    data = W.load()
    source = data["source"]
    summary = W.summary()
    boundary = W.boundary_assessment()
    diffs = W.year_is_exploitation_year()

    out = ["# Zero-days exploited in the wild: the reference set, and what it does not say\n\n",
           f"Generated by `tools/gen_in_the_wild.py` from `vendor/p0_0days/index.json`. "
           f"`test_wild.py` fails if this file and the pinned index disagree.\n\n",
           "## Provenance\n\n",
           f"- Source: [`{source['repo']}`]({source['url']}), Apache-2.0\n",
           f"- Pinned commit: `{source['commit']}` ({source['commit_date']})\n",
           f"- Archive hash: `{source['tarball_sha256']}`\n",
           f"- Snapshot taken: {source['fetched_at']}\n",
           f"- {source['note']}\n\n",
           "Upstream is never read at run time. Updating this set means fetching a new commit, "
           "regenerating the index and reviewing the diff, which is the same rule the vendored "
           "triage engine follows.\n\n",
           "## What is in it\n\n",
           f"{summary['entries']} root-cause analyses across {len(summary['by_year'])} years and "
           f"{summary['products']} distinct products.\n\n",
           "| Year | Entries |\n|------|---------|\n"]
    for year, count in summary["by_year"].items():
        out.append(f"| {year} | {count} |\n")
    out.append("\n| Product | Entries |\n|---------|---------|\n")
    for product, count in summary["top_products"]:
        out.append(f"| {product} | {count} |\n")

    out.append("\n## What it does not say\n\n")
    out.append(boundary["statement"] + "\n\n")
    out.append(f"- Entries whose header mentions persistence or boot artefacts: "
               f"**{boundary['touching_persistence_or_boot']} of {boundary['entries']}**\n")
    for name, count in boundary["by_class"].items():
        out.append(f"- `{name}`: {count}\n")
    if not boundary["by_class"].get("firmware_boot"):
        out.append("- `firmware_boot`: none. This corpus records exploited software 0-days; "
                   "firmware implants such as those modelled elsewhere in this repository are "
                   "not represented here, so its absence is not evidence they do not occur.\n")
    out.append("\nThis corpus is exploitation research, not detection ground truth. It is not "
               "used to tune any rule, and a low overlap with it is expected rather than a "
               "criticism of either project.\n\n")

    out.append("## Data quality, as received\n\n")
    missing_titles = [e["cve"] for e in data["entries"] if not e["title"]]
    missing_dates = [e["cve"] for e in data["entries"] if not e["disclosure_date"]]
    out.append(f"- Entries without a heading title: {len(missing_titles)} "
               f"({', '.join(missing_titles) or 'none'})\n")
    out.append(f"- Entries without a disclosure date: {len(missing_dates)}\n")
    filed = ", ".join(f"{k} filed under {detail['exploited_year']}"
                      for k, detail in diffs.items())
    out.append(f"- Entries where the folder year differs from the CVE year: {len(diffs)} "
               f"({filed})\n")
    out.append("- Upstream files an entry by the year it was found exploited, not the year the "
               "CVE was assigned, so the two can legitimately differ.\n\n")

    out.append("## Classification\n\n")
    out.append("Classes below come from keyword matches over the RCA header, recorded with the "
               "terms that matched so a reviewer can check them. A keyword match is an "
               "observation to adjudicate, not a finding.\n\n")
    out.append("| Class | Keyword families |\n|-------|------------------|\n")
    for name, keywords in W.CLASSES.items():
        out.append(f"| `{name}` | {', '.join(keywords)} |\n")
    return "".join(out)


def main() -> int:
    OUT.write_text(tables.align(render()))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
