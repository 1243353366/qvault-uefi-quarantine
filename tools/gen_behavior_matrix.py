#!/usr/bin/env python3
"""Render report/THREAT_BEHAVIOR_MATRIX.md from the behaviour catalogue.

The document is generated so it cannot drift from the code: a test compares the file against
this renderer, and every row resolves to a real module and symbol before it can appear.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qvault import behaviors as B  # noqa: E402
import tables  # noqa: E402

OUT = ROOT / "report" / "THREAT_BEHAVIOR_MATRIX.md"

HEADER = """# Attacker behaviour to control

Generated by `tools/gen_behavior_matrix.py` from `qvault/behaviors.py`. Do not edit by hand:
`test_behaviors.py` fails if this file and the catalogue disagree.

Each row is a behaviour, the ATT&CK technique that names it, the evidence it leaves, the
control here that answers it, and the limit of that control. Coverage is one of
`implemented`, `partial`, `absent`, and `absent` is a normal value: the point of the table is
that the gaps are visible.

| Behaviour | ATT&CK | Coverage | Control | Limit |
|-----------|--------|----------|---------|-------|
"""


def render() -> str:
    lines = [HEADER]
    for family, entries in B.by_family().items():
        lines.append(f"\n### {family}\n\n")
        lines.append("| Behaviour | ATT&CK | Coverage | Control | Limit |\n")
        lines.append("|-----------|--------|----------|---------|-------|\n")
        for e in entries:
            control = e.control.replace("|", "\\|")
            limit = e.limit.replace("|", "\\|")
            lines.append(f"| `{e.id}` | [{e.attck}](https://attack.mitre.org/techniques/"
                         f"{e.attck.replace('.', '/')}/) — {e.technique} | {e.coverage} | "
                         f"{control} | {limit} |\n")
    summary = B.summary()
    lines.append("\n## Totals\n\n")
    lines.append(f"{summary['behaviours']} behaviours: "
                 + ", ".join(f"{k} {v}" for k, v in summary["by_coverage"].items()) + ".\n")
    gaps = B.gaps()
    lines.append(f"\n{len(gaps)} are not fully answered and are listed as such in the table "
                 f"above. A behaviour in the `absent` rows is not covered by anything in this "
                 f"repository, and no test elsewhere should imply that it is.\n")
    return "".join(lines)


def main() -> int:
    rendered = tables.align(render())
    OUT.write_text(rendered)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
