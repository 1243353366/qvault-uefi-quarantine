#!/usr/bin/env python3
"""Render report/TELEMETRY_MAP.md from qvault/telemetry.py."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qvault import persistence as P  # noqa: E402
from qvault import telemetry as T  # noqa: E402
import tables  # noqa: E402

OUT = ROOT / "report" / "TELEMETRY_MAP.md"

HEADER = """# Telemetry map: what feeds each detection

Generated by `tools/gen_telemetry_map.py` from `qvault/telemetry.py`. `test_telemetry.py` fails
if this file and the mapping disagree.

A detection without a named evidence source is an opinion. Each mechanism below lists the
telemetry that would carry its evidence, the fields to look at, and any published Sigma family
covering the same behaviour. Where a host cannot testify, the row says so and names the source
that sits outside it.

Sysmon event semantics are from the Microsoft Sysinternals documentation; Sigma rule
identifiers were read from the SigmaHQ repository; ATT&CK v20 vocabulary is Detection Strategy,
Analytics and Data Components.

## Mechanisms

| Mechanism | Result class | Evidence sources | Event ids | Sigma family | Blind spot |
|-----------|--------------|------------------|-----------|--------------|------------|
"""


def render() -> str:
    out = [HEADER]
    for mechanism in sorted(P.MECHANISMS):
        definition = P.MECHANISMS[mechanism]
        sources = T.sources(mechanism) if T.MECHANISM_SOURCES.get(mechanism) else []
        sigma = [s for s in T.SIGMA if s.mechanism == mechanism]
        if not definition.observable:
            state = "unknown_not_observable"
        elif not sources:
            state = "no host telemetry"
        else:
            state = "detected / benign"
        names = ", ".join(s.product for s in sources) or "none"
        ids = ", ".join(f"{s.event_ids[0]}" for s in sources) or "-"
        rule = ", ".join(f"[{s.title}](https://github.com/SigmaHQ/sigma/blob/master/{s.path})"
                         for s in sigma) or "-"
        blind = T.NO_TELEMETRY.get(mechanism) or T.EXECUTION_TIME_ONLY.get(mechanism) or "-"
        out.append(f"| `{mechanism}` | {state} | {names} | {ids} | {rule} | {blind} |\n")

    out.append("\n## Sources\n\n| Source | Product | Channel | Event ids | Fields |\n")
    out.append("|--------|---------|---------|-----------|--------|\n")
    for source in sorted(T.SOURCES.values(), key=lambda s: s.id):
        out.append(f"| `{source.id}` | {source.product} | {source.channel} | "
                   f"{', '.join(source.event_ids) or '-'} | "
                   f"{', '.join(source.fields)} |\n")

    out.append("\n## Sigma families cited\n\n")
    for rule in T.SIGMA:
        out.append(f"- *{rule.title}* (`{rule.rule_id}`, logsource `{rule.logsource_category}`) "
                   f"for `{rule.mechanism}`: {rule.note}\n")

    out.append("\n## Blind spots\n\n")
    for item in T.blind_spots():
        out.append(f"- `{item['mechanism']}`: {item['reason']}\n")
    for mechanism, reason in sorted(T.EXECUTION_TIME_ONLY.items()):
        out.append(f"- `{mechanism}`: {reason}\n")
    out.append("\nNo row above is a claim of detection coverage. A mechanism with telemetry and "
               "no deployment is a mechanism nobody is watching.\n")
    return "".join(out)


def main() -> int:
    OUT.write_text(tables.align(render()))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
